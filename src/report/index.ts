/**
 * Markdown bug report generation.
 *
 * The bundle is the artefact; the report is what a human actually pastes into
 * an issue. It has one job: give a maintainer everything they need in the first
 * screen, and a copy-pasteable path to reproduce it in the second. Anything
 * that needs more than that belongs in the bundle, not in the report.
 *
 * The output is deliberately free of absolute paths, hostnames and timings that
 * differ per machine: a report is public the moment it is pasted.
 */

import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { ARCHIVE_SUFFIX } from "../archive/index.js";
import type { Bundle } from "../types.js";
import { formatBytes } from "../util/bytes.js";

const FENCE = "".padEnd(3, String.fromCharCode(96));

export interface ReportOptions {
  readonly bundle: Bundle;
  /** Bundle directory, used to find the log files. */
  readonly root: string;
  /** Name the archive will have once packed; defaults to the bundle id. */
  readonly archiveName?: string;
  /** How many trailing log lines to quote. */
  readonly tailLines?: number;
  /** Include the environment table. Off for very small reports. */
  readonly includeEnvironment?: boolean;
}

export interface Report {
  readonly title: string;
  readonly body: string;
}

/**
 * Build the issue title.
 *
 * Kept under ~80 characters because GitHub truncates longer titles in list
 * views, and a report nobody can tell apart from its neighbours is useless.
 */
/** GitHub clips issue titles around here; past it the suffix is unreadable. */
const TITLE_BUDGET = 80;

/**
 * One-line summary of the failure.
 *
 * The suffix is measured first and the command is truncated to whatever room
 * is left, because "signal SIGABRT" is longer than "exit 1" and a fixed slice
 * silently overshoots the budget on the signal branch.
 */
export function reportTitle(bundle: Bundle): string {
  const command = bundle.command.argv.join(" ");
  const exit = bundle.command.exitCode === null ? "signal " + String(bundle.command.signal) : "exit " + String(bundle.command.exitCode);
  const suffix = " fails (" + exit + ")";
  const room = TITLE_BUDGET - suffix.length;
  if (command.length <= room) return command + suffix;
  return command.slice(0, Math.max(0, room - 3)) + "..." + suffix;
}

export async function buildReport(options: ReportOptions): Promise<Report> {
  const { bundle, root } = options;
  const archive = options.archiveName ?? "bundle" + ARCHIVE_SUFFIX;
  const tailLines = options.tailLines ?? 25;
  const includeEnvironment = options.includeEnvironment ?? true;

  const stderr = await tail(join(root, bundle.command.stderrPath), tailLines);
  const stdout = await tail(join(root, bundle.command.stdoutPath), tailLines);
  const lines: string[] = [];

  lines.push("<!-- generated by repropack " + bundle.producer.version + " -->");
  lines.push("");
  lines.push("A failing run was captured into a self-contained bundle. Replaying it on another");
  lines.push("machine reproduces the same exit code without any of the reporter's files,");
  lines.push("credentials or environment.");
  lines.push("");
  lines.push("## Reproduce");
  lines.push("");
  lines.push(FENCE + "sh");
  // Deliberately not "npx repropack": that name is held by an unrelated
  // package on the registry, and a reporter who runs it would execute somebody
  // else's code. Naming the binary keeps the instruction true for anyone who
  // has the tool installed and is obviously wrong, rather than plausibly wrong,
  // for anyone who does not.
  lines.push("repropack replay " + archive);
  lines.push(FENCE);
  lines.push("");
  lines.push("Or by hand, with nothing installed:");
  lines.push("");
  lines.push(FENCE + "sh");
  // The archive stores bundle files at its root, so the extraction directory
  // has to be created explicitly; `tar -xf x && cd x` would not find replay.sh.
  lines.push("mkdir -p " + dirNameOfArchive(archive));
  lines.push("tar -xf " + archive + " -C " + dirNameOfArchive(archive));
  lines.push("cd " + dirNameOfArchive(archive) + " && ./replay.sh");
  lines.push(FENCE);
  lines.push("");
  lines.push("## What failed");
  lines.push("");
  lines.push("| | |");
  lines.push("|---|---|");
  lines.push("| command | " + cell(bundle.command.argv.join(" ")) + " |");
  lines.push("| exit code | " + cell(bundle.command.exitCode === null ? "killed by " + String(bundle.command.signal) : String(bundle.command.exitCode)) + " |");
  if (bundle.repository) {
    lines.push("| commit | " + cell(bundle.repository.commit) + (bundle.repository.dirty ? " (dirty worktree)" : "") + " |");
  }
  lines.push("| bundle id | " + cell(bundle.id.slice(0, 12)) + " |");
  lines.push("");

  if (stderr.trim().length > 0) {
    lines.push("## stderr (last " + String(tailLines) + " lines)");
    lines.push("");
    lines.push(FENCE);
    lines.push(stderr.trimEnd());
    lines.push(FENCE);
    lines.push("");
  } else if (stdout.trim().length > 0) {
    lines.push("## stdout (last " + String(tailLines) + " lines)");
    lines.push("");
    lines.push(FENCE);
    lines.push(stdout.trimEnd());
    lines.push(FENCE);
    lines.push("");
  }

  if (includeEnvironment) {
    const env = bundle.environment;
    lines.push("## Environment");
    lines.push("");
    lines.push("| | |");
    lines.push("|---|---|");
    lines.push("| os | " + cell(env.platform + " / " + env.arch + " / " + env.release) + " |");
    lines.push("| node | " + cell(env.node + " (abi " + env.nodeAbi + ")") + " |");
    if (env.packageManager) {
      lines.push("| package manager | " + cell(env.packageManager.name + " " + env.packageManager.version) + " |");
    }
    lines.push("| timezone | " + cell(env.timezone) + " |");
    lines.push("| locale | " + cell(env.locale) + " |");
    lines.push("");
  }

  lines.push("## Bundle contents");
  lines.push("");
  lines.push(String(bundle.files.length) + " file(s), " + formatBytes(totalBytes(bundle)) + " of source:");
  lines.push("");
  for (const file of bundle.files.slice(0, 20)) {
    lines.push("- " + FENCE + file.path + FENCE + " (" + file.reason + ", " + formatBytes(file.bytes) + ")");
  }
  if (bundle.files.length > 20) lines.push("- ... and " + String(bundle.files.length - 20) + " more");
  lines.push("");

  if (bundle.redaction.totalMatches > 0) {
    lines.push("## Redaction");
    lines.push("");
    lines.push("This bundle was scanned before it left the reporter's machine:");
    lines.push(String(bundle.redaction.totalMatches) + " potential secret(s) were replaced with placeholders by rules `" + bundle.redaction.rulesVersion + "`.");
    for (const hit of bundle.redaction.byRule.slice(0, 10)) {
      lines.push("- " + hit.rule + ": " + String(hit.count) + " match(es)");
    }
    lines.push("");
    lines.push("Placeholder names look like `REDACTED_GITHUB_TOKEN`. If your reproduction needs a");
    lines.push("real credential, set it yourself before replaying; the bundle never carries one.");
    lines.push("");
  }

  if (bundle.warnings.length > 0) {
    lines.push("## Capture warnings");
    lines.push("");
    for (const warning of bundle.warnings) lines.push("- " + warning);
    lines.push("");
  }

  lines.push("---");
  lines.push("Integrity: `" + bundle.integrity + "`. Check with `repropack verify` before");
  lines.push("trusting the bundle's contents.");

  return { title: reportTitle(bundle), body: lines.join("\n") + "\n" };
}

async function tail(path: string, count: number): Promise<string> {
  try {
    const text = await readFile(path, "utf8");
    const all = text.split(/\r?\n/);
    // A trailing newline would produce one empty element; dropping it keeps
    // "last 25 lines" honest.
    if (all.length > 0 && all[all.length - 1] === "") all.pop();
    return all.slice(Math.max(0, all.length - count)).join("\n");
  } catch {
    return "";
  }
}

function totalBytes(bundle: Bundle): number {
  return bundle.files.reduce((sum, file) => sum + file.bytes, 0);
}

/** Escape a value for a markdown table cell. */
function cell(value: string): string {
  return "`" + value.split("`").join("'" ) + "`";
}

function dirNameOfArchive(archive: string): string {
  return archive.replace(/\.repropack$/, "");
}